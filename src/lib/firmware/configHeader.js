import { badRequest } from '../errors.js'
import { pinLabel } from '../hardwareRules.js'

function cString(value, field) {
  const s = String(value ?? '')
  if (/[\r\n\0]/.test(s)) throw badRequest(`${field} must not contain line breaks`)
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

// A PEM certificate as a C string literal, one line per source line.
const pemLiteral = (pem) =>
  pem
    .trim()
    .split(/\r?\n/)
    .map((l) => `  "${l}\\n"`)
    .join('\n')

// config.h for the shared firmware template (firmware/acls_firmware). Pins and trigger level come
// from the device's channels and hardware profile; nothing is invented here.
// mqtt: { tls, ca, username, password } for an external broker (cloud); omitted = the built-in broker,
// where each board logs in with its own name and secret. buildId lets the server see which build runs.
export function buildConfigHeader({ device, profile, channels, room, settings, secret, wifiSsid, wifiPassword, mqtt, buildId }) {
  const sorted = [...channels].sort((a, b) => a.index - b.index)
  const pins = sorted.map((c) => c.gpio)
  const pinComments = sorted.map((c) => `IN${c.index}=${pinLabel(profile.espModel, c.gpio)}/GPIO${c.gpio}`).join(', ')
  const on = profile.trigger
  const off = on === 'HIGH' ? 'LOW' : 'HIGH'
  const led = profile.statusLed?.gpio ?? -1
  const lines = [
    '// ACLS device configuration: generated by the ACLS website. Do not edit by hand;',
    '// regenerate it from the device page instead. Keep this file private: it holds the device secret.',
    `// Device: ${device.name} (${device.deviceId})  Room: ${room?.displayName ?? 'unassigned'}`,
    `// Profile: ${profile.code} v${profile.version}, ${profile.espBoard} + ${profile.relayModule}${profile.verified ? '' : '  ** UNVERIFIED PROFILE: bench test only **'}`,
    `// Generated: ${new Date().toISOString()}`,
    '#pragma once',
    '',
    `// For firmware template ${settings.firmwareVersion} (the version is defined in acls_firmware.ino)`,
    `#define ACLS_PROFILE "${profile.code} v${profile.version}"`,
    profile.espModel === 'esp8266' ? '#define ACLS_BOARD_ESP8266 1' : '#define ACLS_BOARD_ESP32 1',
    '',
    `#define DEVICE_ID ${cString(device.deviceId, 'deviceId')}`,
    '',
    `// ${pinComments}`,
    `#define RELAY_COUNT ${pins.length}`,
    `#define RELAY_PIN_LIST {${pins.join(', ')}}`,
    `#define RELAY_ON ${on}${profile.triggerNote ? `   // ${profile.triggerNote}` : ''}`,
    `#define RELAY_OFF ${off}`,
    '',
    `#define STATUS_LED_PIN ${led}${led === -1 ? '   // no status LED defined for this board' : ''}`,
    `#define STATUS_LED_ON ${profile.statusLed?.activeLow === false ? 'HIGH' : 'LOW'}`,
    '',
    '// Phase 1: WiFi is set here. Phase 2 replaces this with the setup portal.',
    `#define WIFI_SSID ${cString(wifiSsid, 'WiFi name')}`,
    `#define WIFI_PASSWORD ${cString(wifiPassword, 'WiFi password')}`,
    '',
    `#define MQTT_HOST ${cString(settings.brokerHost, 'brokerHost')}`,
    `#define MQTT_PORT ${Number(settings.brokerPort)}`,
    `#define MQTT_USER ${cString(mqtt ? mqtt.username : device.mqttUsername, 'mqttUsername')}`,
    `#define MQTT_PASSWORD ${cString(mqtt ? mqtt.password : secret, 'secret')}`,
    `#define TOPIC_ROOT ${cString(settings.topicRoot, 'topicRoot')}`,
    `#define ACLS_BUILD ${cString(buildId ?? '', 'buildId')}`,
    '',
  ]
  if (mqtt?.tls) {
    lines.push('// Encrypted connection (TLS). The board checks the broker against this root certificate;', '// without one it encrypts but cannot tell a fake broker from the real one.')
    lines.push('#define MQTT_TLS 1')
    if (mqtt.ca) lines.push('static const char MQTT_CA_CERT[] =', `${pemLiteral(mqtt.ca)};`, '#define MQTT_HAS_CA 1')
    lines.push('')
  }
  return lines.join('\n')
}
